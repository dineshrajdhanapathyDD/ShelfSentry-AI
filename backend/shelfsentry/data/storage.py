# ---------------------------------------------------------------------------
# Errors
# ---------------------------------------------------------------------------


class StorageError(Exception):
    """Base class for storage-layer failures."""


class InvalidMediaRef(StorageError, ValueError):
    """A media reference (or record id used as a filename) is malformed or
    would escape the configured base directory.

    Raised *before* any file is opened so a crafted reference cannot be used to
    traverse the filesystem (Req 9). Carries no absolute path in its message so
    it does not widen the security boundary.
    """


class RecordNotFound(StorageError, LookupError):
    """The requested media/report/job does not exist in this store."""


# ---------------------------------------------------------------------------
# Small record / query types exchanged across the StorageAdapter seam
# ---------------------------------------------------------------------------

#: A media reference is an opaque, server-minted handle with this scheme. The
#: part after the scheme is a pure-hex token generated by the adapter.
MEDIA_REF_SCHEME = "media://"

#: Lifecycle of an async inspection job (Req 19.4). ``queued`` -> ``running``
#: -> terminal ``succeeded``/``failed``.
JobStatus = Literal["queued", "running", "succeeded", "failed"]


class JobRecord(CanonicalModel):
    """A small record tracking an async inspection job (Req 19.4).

    Persisted as JSON. Inherits the canonical serialization + strict boundary
    validation of :class:`~shelfsentry.data.contracts.CanonicalModel`, so two
    equal jobs serialize identically and malformed data is rejected with a
    field-identifying error.
    """

    job_id: str = Field(..., min_length=1, description="Unique job identifier.")
    inspection_id: str = Field(
        ..., min_length=1, description="Inspection this job runs."
    )
    status: JobStatus = Field(..., description="Current lifecycle status.")
    created_at: str = Field(
        ..., min_length=1, description="ISO-8601 creation timestamp."
    )
    updated_at: str = Field(
        ..., min_length=1, description="ISO-8601 last-update timestamp."
    )
    error: str | None = Field(
        default=None, description="Failure detail when status is 'failed'."
    )


class InspectionSummary(BaseModel):
    """A compact History-list row derived from a stored
    :class:`~shelfsentry.data.contracts.InspectionReport` (Req 13.1).

    Returned by :meth:`StorageAdapter.list_reports`. It is a projection of the
    full report (never a second source of truth), carrying only what the
    History list needs: id, mode, status, the final recommendation, the
    human-review flag, and the creation timestamp.
    """

    model_config = ConfigDict(extra="forbid")

    inspection_id: str
    mode: Literal["local", "aws"]
    status: Literal["complete", "failed", "needs_review"]
    final_recommendation: str
    requires_human_review: bool
    created_at: str

    @classmethod
    def from_report(cls, report: InspectionReport) -> "InspectionSummary":
        """Project a full report down to its History summary row."""
        return cls(
            inspection_id=report.inspection_id,
            mode=report.mode,
            status=report.status,
            final_recommendation=report.final_recommendation,
            requires_human_review=report.requires_human_review,
            created_at=report.created_at,
        )


class HistoryQuery(BaseModel):
    """Filters for :meth:`StorageAdapter.list_reports` (Req 13.1, 13.2).

    All fields are optional. ``status`` restricts to one report status; ``text``
    is a case-insensitive substring matched against the inspection id and the
    final recommendation; ``limit`` caps the number of returned rows (newest
    first). An empty query returns every report (up to ``limit``).
    """

    model_config = ConfigDict(extra="forbid")

    status: Literal["complete", "failed", "needs_review"] | None = Field(
        default=None, description="Restrict to one report status."
    )
    text: str | None = Field(
        default=None,
        description="Case-insensitive substring over inspection_id + recommendation.",
    )
    limit: int | None = Field(
        default=None, ge=1, description="Maximum rows to return (newest first)."
    )


