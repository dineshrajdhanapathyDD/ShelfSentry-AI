"""Persistence abstraction for ShelfSentry AI (task 10.1; Req 15.4, 16.1).

This module defines the single :class:`StorageAdapter` seam between the
mode-agnostic core and mode-specific persistence (design.md "Data Layer"), the
small record/query types it exchanges, the local on-disk implementation
(:class:`LocalStorageAdapter`), and a thin shim
(:class:`StorageMediaResolver`) that lets any adapter satisfy the MCP
:class:`shelfsentry.mcp.MediaResolver` Protocol.

Design references: design.md "Data Layer" (the ``StorageAdapter`` Protocol with
``put_media``/``get_media``, ``save_report``/``get_report``, ``list_reports``,
and ``save_job``/``get_job``) and "Security boundary" (Req 9): media is
addressed only by server-generated opaque references and inspection-scoped ids,
never by a filesystem path or URL supplied by a caller.

Security boundary (Req 9, enforced structurally here).
    A media *reference* is a server-minted opaque handle of the form
    ``media://<hex-token>``; the hex token is generated by
    :class:`LocalStorageAdapter`, never accepted from the agent. On every read,
    the token is re-validated to be pure lowercase hex of the expected length
    and the resolved file path is confirmed to live inside the configured media
    directory, so a *crafted* reference (``../``, an absolute path, a URL, a
    drive letter, a NUL byte, ...) cannot traverse out of the base directory -
    it is rejected with :class:`InvalidMediaRef` before any file is opened.
    Record ids used for on-disk filenames (``inspection_id``, ``job_id``) are
    likewise sanitized and scope-checked the same way.

Determinism / no network.
    :class:`LocalStorageAdapter` touches only the local filesystem: JSON files
    for reports and jobs, raw bytes for media, plus a tiny JSON media manifest
    mapping inspection-scoped slots (the per-inspection original image, each
    named frame, and each finding's stored evidence) to their opaque refs. No
    socket, no clock-dependent behavior in a stored record's identity, and no
    randomness other than the opaque media token (which is explicitly an opaque
    handle, not addressable content).
"""

from __future__ import annotations

import json
import os
