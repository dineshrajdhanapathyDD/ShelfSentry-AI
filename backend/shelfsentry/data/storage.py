@runtime_checkable
class StorageAdapter(Protocol):
    """The persistence seam between mode-agnostic logic and mode-specific
    storage (design.md "Data Layer"; Req 15.4, 16.1).

    Media is addressed only by opaque, server-minted references
    (``put_media`` returns one; ``get_media`` resolves one). Reports and jobs
    are addressed by their ids. The local and AWS implementations both satisfy
    this Protocol so the identical pipeline runs in either mode.
    """

    def put_media(self, inspection_id: str, data: bytes, kind: str) -> str:
        """Store media bytes for an inspection and return an opaque reference.

        ``kind`` is an inspection-scoped slot label (e.g. ``"image"`` for the
        primary image, or ``"frame:<frame_id>"`` / ``"evidence:<finding_id>"``);
        the returned reference is a server-minted handle, never a path or URL.
        """
        ...

    def get_media(self, ref: str) -> bytes:
        """Return the bytes previously stored under the opaque ``ref``."""
        ...

    def save_report(self, report: InspectionReport) -> None:
        """Persist (create or overwrite) an inspection report."""
        ...

    def get_report(self, inspection_id: str) -> InspectionReport | None:
        """Return the stored report for ``inspection_id``, or ``None``."""
        ...

    def list_reports(self, query: HistoryQuery) -> list[InspectionSummary]:
        """Return History summaries matching ``query`` (newest first)."""
        ...

    def save_job(self, job: JobRecord) -> None:
        """Persist (create or overwrite) an async job record (Req 19.4)."""
        ...

    def get_job(self, job_id: str) -> JobRecord | None:
        """Return the stored job for ``job_id``, or ``None``."""
        ...


