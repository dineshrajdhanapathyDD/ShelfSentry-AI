# Local, on-disk implementation (Req 15.4)
# ---------------------------------------------------------------------------

# A minted media token is this many random bytes rendered as lowercase hex.
_MEDIA_TOKEN_BYTES = 16
_MEDIA_TOKEN_HEX_LEN = _MEDIA_TOKEN_BYTES * 2
_HEX_TOKEN_RE = re.compile(r"\A[0-9a-f]{%d}\Z" % _MEDIA_TOKEN_HEX_LEN)

# A safe record id used as a filename stem: letters, digits, and a small set of
# separators only. Anything else (``/``, ``\\``, ``..``, ``:``, NUL, ...) is
# rejected so a crafted id cannot escape the records directory.
_SAFE_ID_RE = re.compile(r"\A[A-Za-z0-9][A-Za-z0-9._-]{0,127}\Z")


def _sanitize_record_id(raw: str, *, what: str) -> str:
    """Validate ``raw`` as a safe on-disk record id, or raise.

    Rejects ids that are empty, over-long, contain a path separator, a ``..``
    segment, a drive letter, a NUL byte, or any character outside the safe set.
    Returns the id unchanged when it is safe (it is used only as a filename
    stem, never joined with caller-controlled sub-paths).
    """
    if not isinstance(raw, str) or not _SAFE_ID_RE.match(raw) or ".." in raw:
        raise InvalidMediaRef(f"unsafe {what} id")
    return raw


class LocalStorageAdapter:
    """Local filesystem :class:`StorageAdapter`: JSON records + files on disk
    under a configurable base directory (Req 15.4).

    Layout under ``base_dir``::

        base_dir/
            media/<token>.bin          # raw media bytes, keyed by opaque token
            media/manifest.json        # inspection-scoped slot -> ref map
            reports/<inspection_id>.json
            jobs/<job_id>.json

    The implementation is deterministic and performs no network I/O. Writes are
    atomic (written to a temp file in the same directory, then ``os.replace``)
    so a concurrent reader never sees a half-written JSON record.
    """

    def __init__(self, base_dir: str | os.PathLike[str]) -> None:
        """Create the adapter rooted at ``base_dir`` (created if absent)."""
        self._base = Path(base_dir).resolve()
        self._media_dir = self._base / "media"
        self._reports_dir = self._base / "reports"
        self._jobs_dir = self._base / "jobs"
        for d in (self._media_dir, self._reports_dir, self._jobs_dir):
            d.mkdir(parents=True, exist_ok=True)
        self._manifest_path = self._media_dir / "manifest.json"

    # -- internal helpers -----------------------------------------------------

    @staticmethod
    def _atomic_write_bytes(path: Path, data: bytes) -> None:
        """Write ``data`` to ``path`` atomically within its directory."""
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=str(path.parent), suffix=".tmp")
        try:
            with os.fdopen(fd, "wb") as fh:
                fh.write(data)
            os.replace(tmp, path)
        finally:
            if os.path.exists(tmp):  # pragma: no cover - cleanup on error path
                os.unlink(tmp)

    def _atomic_write_text(self, path: Path, text: str) -> None:
        self._atomic_write_bytes(path, text.encode("utf-8"))

    def _media_path_for_token(self, token: str) -> Path:
        """Resolve an opaque token to its on-disk media path, safely.

        The token is validated to be pure lowercase hex of the expected length,
        and the resolved path is confirmed to live directly inside the media
        directory. A crafted token therefore cannot traverse out of the base
        directory (Req 9).
        """
        if not isinstance(token, str) or not _HEX_TOKEN_RE.match(token):
            raise InvalidMediaRef("malformed media reference")
        candidate = (self._media_dir / f"{token}.bin").resolve()
        # Defense in depth: confirm containment even though the regex already
        # forbids separators and dots in the token.
        if candidate.parent != self._media_dir:
            raise InvalidMediaRef("media reference escapes the media directory")
        return candidate

    def _parse_ref(self, ref: str) -> str:
        """Extract and validate the hex token from an opaque media ``ref``."""
        if not isinstance(ref, str) or not ref.startswith(MEDIA_REF_SCHEME):
            raise InvalidMediaRef("media reference has an unexpected scheme")
        return ref[len(MEDIA_REF_SCHEME) :]

    def _load_manifest(self) -> dict[str, dict[str, str]]:
        if not self._manifest_path.exists():
            return {}
        try:
            data = json.loads(self._manifest_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):  # pragma: no cover - corrupt manifest
            return {}
        return data if isinstance(data, dict) else {}

    def _save_manifest(self, manifest: dict[str, dict[str, str]]) -> None:
        self._atomic_write_text(
            self._manifest_path,
            json.dumps(manifest, sort_keys=True, separators=(",", ":")),
        )

    # -- media ----------------------------------------------------------------

    def put_media(self, inspection_id: str, data: bytes, kind: str) -> str:
        """Store media bytes and return a fresh opaque reference (Req 9).

        A new random hex token is minted for every call; the bytes are written
        to ``media/<token>.bin`` and the ``(inspection_id, kind)`` slot is
        recorded in the manifest so the resolver shim can address media by
        inspection-scoped id/kind without the caller ever handling a path.
        """
        _sanitize_record_id(inspection_id, what="inspection")
        if not isinstance(data, (bytes, bytearray)):
            raise InvalidMediaRef("media data must be bytes")
        token = secrets.token_hex(_MEDIA_TOKEN_BYTES)
        path = self._media_path_for_token(token)
        self._atomic_write_bytes(path, bytes(data))
        ref = f"{MEDIA_REF_SCHEME}{token}"

        manifest = self._load_manifest()
        manifest.setdefault(inspection_id, {})[str(kind)] = ref
        self._save_manifest(manifest)
        return ref

    def get_media(self, ref: str) -> bytes:
        """Return the bytes stored under an opaque ``ref`` (Req 9).

        The reference's token is validated and scope-checked before any file is
        opened, so a crafted ref cannot read outside the media directory.
        """
        token = self._parse_ref(ref)
        path = self._media_path_for_token(token)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise RecordNotFound("media not found") from exc

    def get_media_ref_for(self, inspection_id: str, kind: str) -> str | None:
        """Return the opaque ref recorded for an inspection slot, or ``None``.

        Used by :class:`StorageMediaResolver` to map inspection-scoped id/kind
        to the stored media without exposing a path.
        """
        manifest = self._load_manifest()
        return manifest.get(inspection_id, {}).get(str(kind))

    # -- reports --------------------------------------------------------------

    def _report_path(self, inspection_id: str) -> Path:
        safe = _sanitize_record_id(inspection_id, what="inspection")
        return self._reports_dir / f"{safe}.json"

    def save_report(self, report: InspectionReport) -> None:
        """Persist a report as canonical JSON under its inspection id."""
        path = self._report_path(report.inspection_id)
        self._atomic_write_text(path, report.canonical_json())

    def get_report(self, inspection_id: str) -> InspectionReport | None:
        """Load the stored report for ``inspection_id``, or ``None``."""
        try:
            path = self._report_path(inspection_id)
        except InvalidMediaRef:
            return None
        if not path.exists():
            return None
        return InspectionReport.model_validate_json(path.read_text(encoding="utf-8"))

    def list_reports(self, query: HistoryQuery) -> list[InspectionSummary]:
        """Return History summaries matching ``query`` (newest first).

        Supports a ``status`` filter, a case-insensitive ``text`` substring
        search over the inspection id + final recommendation, and a ``limit``
        (Req 13.1, 13.2). Rows are ordered by ``created_at`` descending, then by
        inspection id, so the order is deterministic.
        """
        summaries: list[InspectionSummary] = []
        for path in self._reports_dir.glob("*.json"):
            try:
                report = InspectionReport.model_validate_json(
                    path.read_text(encoding="utf-8")
                )
            except (OSError, ValueError):  # pragma: no cover - skip unreadable
                continue
            summaries.append(InspectionSummary.from_report(report))

        if query.status is not None:
            summaries = [s for s in summaries if s.status == query.status]
        if query.text:
            needle = query.text.strip().lower()
            if needle:
                summaries = [
                    s
                    for s in summaries
                    if needle in s.inspection_id.lower()
                    or needle in s.final_recommendation.lower()
                ]

        summaries.sort(key=lambda s: (s.created_at, s.inspection_id), reverse=True)
        if query.limit is not None:
            summaries = summaries[: query.limit]
        return summaries

    # -- jobs -----------------------------------------------------------------

    def _job_path(self, job_id: str) -> Path:
        safe = _sanitize_record_id(job_id, what="job")
        return self._jobs_dir / f"{safe}.json"

    def save_job(self, job: JobRecord) -> None:
        """Persist an async job record as canonical JSON (Req 19.4)."""
        path = self._job_path(job.job_id)
        self._atomic_write_text(path, job.canonical_json())

    def get_job(self, job_id: str) -> JobRecord | None:
        """Load the stored job for ``job_id``, or ``None``."""
        try:
            path = self._job_path(job_id)
        except InvalidMediaRef:
            return None
        if not path.exists():
            return None
        return JobRecord.model_validate_json(path.read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# MediaResolver shim (satisfies shelfsentry.mcp.MediaResolver)
# ---------------------------------------------------------------------------

# Inspection-scoped slot labels used in the media manifest. The primary image
# lives under a fixed label; frames and evidence are namespaced by their ids so
# distinct frames/findings never collide.
_IMAGE_SLOT = "image"


def _frame_slot(frame_id: str) -> str:
    return f"frame:{frame_id}"


def _evidence_slot(finding_id: str) -> str:
    return f"evidence:{finding_id}"


class StorageMediaResolver:
    """Adapt a :class:`LocalStorageAdapter` to the MCP ``MediaResolver`` Protocol.

    The MCP server (task 9.1) resolves media only by inspection-scoped ids
    through a :class:`shelfsentry.mcp.MediaResolver`; this shim maps those calls
    onto storage operations so the concrete adapter can back the server without
    the server ever importing a storage adapter or handling a path/URL
    (preserving the Req 9 boundary). Media stays addressed by inspection-scoped
    ids: the per-inspection original image under a fixed ``image`` slot, frames
    under ``frame:<frame_id>``, and evidence under ``evidence:<finding_id>``.
    """

    def __init__(self, adapter: LocalStorageAdapter) -> None:
        self._adapter = adapter

    def get_image(self, inspection_id: str) -> bytes:
        """Return the inspection's primary image bytes (MediaResolver)."""
        ref = self._adapter.get_media_ref_for(inspection_id, _IMAGE_SLOT)
        if ref is None:
            raise RecordNotFound("no image for inspection")
        return self._adapter.get_media(ref)

    def get_frame(self, inspection_id: str, frame_id: str) -> bytes:
        """Return the bytes of a named frame within the inspection."""
        ref = self._adapter.get_media_ref_for(inspection_id, _frame_slot(frame_id))
        if ref is None:
            raise RecordNotFound("no such frame for inspection")
        return self._adapter.get_media(ref)

    def put_evidence(self, inspection_id: str, finding_id: str, data: bytes) -> str:
        """Store annotated-evidence bytes and return an opaque reference."""
        return self._adapter.put_media(
            inspection_id, data, _evidence_slot(finding_id)
        )

    def get_evidence_ref(self, inspection_id: str, finding_id: str) -> str | None:
        """Return the stored evidence reference for a finding, or ``None``."""
        return self._adapter.get_media_ref_for(
            inspection_id, _evidence_slot(finding_id)
        )

    # Convenience writers used by the local pipeline to seed resolver-addressable
    # media without the caller tracking slot labels. Not part of the Protocol.

    def put_image(self, inspection_id: str, data: bytes) -> str:
        """Store the inspection's primary image under the fixed image slot."""
        return self._adapter.put_media(inspection_id, data, _IMAGE_SLOT)

    def put_frame(self, inspection_id: str, frame_id: str, data: bytes) -> str:
        """Store a named frame under this inspection."""
        return self._adapter.put_media(inspection_id, data, _frame_slot(frame_id))
